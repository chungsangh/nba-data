"""Generate METRICS.md from the dbt semantic manifest and enforce metric governance rules.

    uv run python scripts/metrics_catalog.py            # rewrite METRICS.md
    uv run python scripts/metrics_catalog.py --check    # fail if METRICS.md is stale or rules break

Rules:
  1. Every metric is either published (has meta.owner and meta.tier) or a building block
     (a simple metric auto-created from a measure of the same name via create_metric).
  2. tier is one of: certified, experimental.
  3. A certified metric may not depend on an experimental metric.

Run `dbt parse` first so transform/target/semantic_manifest.json is current.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "transform" / "target" / "semantic_manifest.json"
CATALOG = ROOT / "METRICS.md"
TIERS = ("certified", "experimental")


def load_manifest(path: Path = MANIFEST) -> dict:
    if not path.exists():
        sys.exit(f"{path} not found: run `dbt parse` in transform/ first")
    return json.loads(path.read_text())


def metric_inputs(metric: dict) -> list[str]:
    """Names of metrics a metric is built from (ratio, derived, cumulative)."""
    params = metric["type_params"]
    names = [m["name"] for m in params.get("metrics") or []]
    for side in ("numerator", "denominator"):
        if params.get(side):
            names.append(params[side]["name"])
    cumulative = params.get("cumulative_type_params") or {}
    if cumulative.get("metric"):
        names.append(cumulative["metric"]["name"])
    return names


def is_building_block(metric: dict) -> bool:
    measure = metric["type_params"].get("measure") or {}
    return metric["type"] == "simple" and measure.get("name") == metric["name"]


def governance_errors(metrics: list[dict]) -> list[str]:
    errors = []
    by_name = {m["name"]: m for m in metrics}
    for m in metrics:
        meta = (m.get("config") or {}).get("meta") or {}
        if is_building_block(m) and not meta:
            continue
        if not meta.get("owner"):
            errors.append(f"{m['name']}: missing meta.owner")
        if meta.get("tier") not in TIERS:
            errors.append(
                f"{m['name']}: meta.tier must be one of {TIERS}, got {meta.get('tier')!r}"
            )
        if meta.get("tier") == "certified":
            for dep in metric_inputs(m):
                dep_tier = ((by_name.get(dep, {}).get("config") or {}).get("meta") or {}).get(
                    "tier"
                )
                if dep_tier == "experimental":
                    errors.append(f"{m['name']}: certified metric depends on experimental {dep}")
    return errors


def _input(ref: dict) -> str:
    """`name`, plus its filter with the Jinja stripped: `shots_made` where shot__shot_zone = ..."""
    text = f"`{ref['name']}`"
    filters = (ref.get("filter") or {}).get("where_filters") or []
    if filters:
        where = " and ".join(
            re.sub(r"\{\{\s*\w+\('([^']+)'\)\s*\}\}", r"\1", f["where_sql_template"])
            for f in filters
        )
        text += f" where {where}"
    return text


def _definition(metric: dict) -> str:
    params = metric["type_params"]
    kind = metric["type"]
    if kind == "simple":
        return f"`{params['measure']['name']}`"
    if kind == "ratio":
        return f"{_input(params['numerator'])} / {_input(params['denominator'])}"
    if kind == "derived":
        return f"`{params['expr']}`"
    if kind == "cumulative":
        cumulative = params.get("cumulative_type_params") or {}
        window = cumulative.get("window") or params.get("window")
        span = f"trailing {window['count']} {window['granularity']}s" if window else "running total"
        source = (cumulative.get("metric") or params.get("measure") or {}).get("name")
        return f"{span} of `{source}`"
    return kind


def _cell(text: str | None) -> str:
    return " ".join((text or "").split()).replace("|", "\\|")


def render(manifest: dict) -> str:
    metrics = sorted(manifest["metrics"], key=lambda m: m["name"])
    published = [m for m in metrics if (m.get("config") or {}).get("meta")]
    blocks = [m for m in metrics if m not in published]
    semantic_models = {sm["name"]: sm for sm in manifest["semantic_models"]}

    lines = [
        "# Metrics catalog",
        "",
        "<!-- Generated by scripts/metrics_catalog.py from the dbt semantic manifest. "
        "Do not edit by hand. -->",
        "",
        "Query any metric with MetricFlow, e.g.",
        "`mf query --metrics offensive_rating --group-by team__team_abbreviation`.",
        "",
        "- **certified**: reviewed, known-answer tested, safe to publish.",
        "- **experimental**: useful, with a documented caveat; may change without notice.",
        "",
    ]
    for tier in TIERS:
        rows = [m for m in published if m["config"]["meta"].get("tier") == tier]
        lines += [
            f"## {tier.capitalize()} ({len(rows)})",
            "",
            "| Metric | Label | Type | Definition | Owner | Description |",
            "|---|---|---|---|---|---|",
        ]
        lines += [
            f"| `{m['name']}` | {_cell(m.get('label'))} | {m['type']} | {_cell(_definition(m))} "
            f"| {m['config']['meta']['owner']} | {_cell(m.get('description'))} |"
            for m in rows
        ]
        lines.append("")

    lines += [
        f"## Saved queries ({len(manifest['saved_queries'])})",
        "",
        "| Saved query | Metrics | Group by | Description |",
        "|---|---|---|---|",
    ]
    for sq in sorted(manifest["saved_queries"], key=lambda q: q["name"]):
        params = sq["query_params"]
        group_by = ", ".join(g.split("'")[1] for g in params["group_by"])
        lines.append(
            f"| `{sq['name']}` | {', '.join(params['metrics'])} | {group_by} "
            f"| {_cell(sq.get('description'))} |"
        )
    lines += [
        "",
        f"## Building blocks ({len(blocks)})",
        "",
        "Simple metrics auto-created from measures (`create_metric: true`) to feed the metrics "
        "above. Prefer the published metrics.",
        "",
        ", ".join(f"`{m['name']}`" for m in blocks),
        "",
        f"## Semantic models ({len(semantic_models)})",
        "",
        "| Semantic model | Gold model | Description |",
        "|---|---|---|",
    ]
    for name, sm in sorted(semantic_models.items()):
        lines.append(
            f"| `{name}` | `{sm['node_relation']['alias']}` | {_cell(sm.get('description'))} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing")
    parser.add_argument("--manifest", type=Path, default=MANIFEST, help="semantic_manifest.json")
    args = parser.parse_args(argv)

    manifest = load_manifest(args.manifest)
    errors = governance_errors(manifest["metrics"])
    for error in errors:
        print(f"governance: {error}", file=sys.stderr)

    content = render(manifest)
    if args.check:
        current = CATALOG.read_text() if CATALOG.exists() else ""
        if current != content:
            print("METRICS.md is out of date: run `make metrics-catalog`", file=sys.stderr)
            return 1
    else:
        CATALOG.write_text(content)
        print(f"Wrote {CATALOG.relative_to(ROOT)}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
